# ---------------- 字体与样式常量 ----------------
FONT_EA = "宋体"
FONT_EA_HEAD = "黑体"
FONT_ASCII = "Times New Roman"
FONT_ASCII_HEAD = "Arial"
DARK = RGBColor(0x1F, 0x37, 0x64)
GREY = RGBColor(0x59, 0x59, 0x59)
RED = RGBColor(0xA6, 0x1B, 0x1B)

USABLE_CM = 16.0  # A4 纵向、左右各 2.5cm 后的可用宽度


def set_run_font(run, ea=FONT_EA, ascii_=FONT_ASCII, size=10.5,
                 bold=False, italic=False, color=None):
    """设置 run 的中西文字体（中文必须设 w:eastAsia）。"""
    run.font.name = ascii_
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    if color is not None:
        run.font.color.rgb = color
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rPr.append(rFonts)
    rFonts.set(qn("w:ascii"), ascii_)
    rFonts.set(qn("w:hAnsi"), ascii_)
    rFonts.set(qn("w:eastAsia"), ea)
    rFonts.set(qn("w:cs"), ascii_)


def _add_runs(p, text, ea=FONT_EA, ascii_=FONT_ASCII, size=10.5, bold=False,
              italic=False, color=None):
    """把文本写入段落，支持 `**加粗**` 内联标记。

    DOCX 不解析 Markdown，因此这里显式把 `**...**` 转成真正的加粗 run，
    避免星号直接出现在正文里。
    """
    if "**" not in text:
        run = p.add_run(text)
        set_run_font(run, ea=ea, ascii_=ascii_, size=size, bold=bold,
                     italic=italic, color=color)
        return p
    for i, seg in enumerate(text.split("**")):
        if not seg:
            continue
        run = p.add_run(seg)
        set_run_font(run, ea=ea, ascii_=ascii_, size=size,
                     bold=(bold or (i % 2 == 1)), italic=italic, color=color)
    return p


def para(doc, text="", size=10.5, bold=False, italic=False, color=None,
         align=None, space_before=0, space_after=4, indent_first=0.0,
         line_spacing=1.35, ea=FONT_EA):
    """添加正文段落（支持 `**加粗**`）。"""
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.space_before = Pt(space_before)
    pf.space_after = Pt(space_after)
    pf.line_spacing = line_spacing
    if indent_first:
        pf.first_line_indent = Cm(indent_first)
    if align is not None:
        p.alignment = align
    if text:
        _add_runs(p, text, ea=ea, size=size, bold=bold, italic=italic,
                  color=color)
    return p


def heading(doc, text, level=1):
    """添加章/节标题（不使用内置样式，避免字体不生效）。"""
    if level == 1:
        p = doc.add_paragraph()
        p.paragraph_format.space_before = Pt(14)
        p.paragraph_format.space_after = Pt(8)
        p.paragraph_format.line_spacing = 1.25
        run = p.add_run(text)
        set_run_font(run, ea=FONT_EA_HEAD, ascii_=FONT_ASCII_HEAD,
                     size=15, bold=True, color=DARK)
        _bottom_border(p)
        return p
    if level == 2:
        p = doc.add_paragraph()
        p.paragraph_format.space_before = Pt(10)
        p.paragraph_format.space_after = Pt(5)
        run = p.add_run(text)
        set_run_font(run, ea=FONT_EA_HEAD, ascii_=FONT_ASCII_HEAD,
                     size=12.5, bold=True, color=DARK)
        return p
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(7)
    p.paragraph_format.space_after = Pt(4)
    run = p.add_run(text)
    set_run_font(run, ea=FONT_EA_HEAD, ascii_=FONT_ASCII_HEAD,
                 size=11, bold=True)
    return p


def _bottom_border(p):
    """给段落加下边框（标题装饰线）。"""
    pPr = p._element.get_or_add_pPr()
    borders = OxmlElement("w:pBdr")
    bottom = OxmlElement("w:bottom")
    bottom.set(qn("w:val"), "single")
    bottom.set(qn("w:sz"), "8")
    bottom.set(qn("w:space"), "3")
    bottom.set(qn("w:color"), "1F3764")
    borders.append(bottom)
    pPr.append(borders)


def note(doc, text, size=9.5):
    """灰色小字说明。"""
    return para(doc, text, size=size, color=GREY, space_after=6,
                line_spacing=1.25)


def bullet(doc, text, size=10.5, level=0):
    """项目符号（手动加符号，避免列表样式字体问题）。"""
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.space_before = Pt(0)
    pf.space_after = Pt(3)
    pf.line_spacing = 1.3
    pf.left_indent = Cm(0.75 + 0.6 * level)
    pf.first_line_indent = Cm(-0.45)
    _add_runs(p, ("● " if level == 0 else "○ ") + text, size=size)
    return p


def _no_split(row):
    """禁止表格行跨页断开（w:cantSplit），避免一行被切成两半。"""
    trPr = row._tr.get_or_add_trPr()
    cs = OxmlElement("w:cantSplit")
    trPr.append(cs)


def table(doc, headers, rows, widths=None, size=9.5, header_size=9.5,
          caption=None, align_center_cols=None):
    """添加表格。widths 为各列宽度（cm），总和应为 16。"""
    if caption:
        cp = doc.add_paragraph()
        cp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        cp.paragraph_format.space_before = Pt(6)
        cp.paragraph_format.space_after = Pt(2)
        r = cp.add_run(caption)
        set_run_font(r, ea=FONT_EA_HEAD, size=9.5, bold=True, color=DARK)

    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    align_center_cols = align_center_cols or set()

    hdr = t.rows[0].cells
    for i, h in enumerate(headers):
        hdr[i].text = ""
        p = hdr[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_before = Pt(2)
        p.paragraph_format.space_after = Pt(2)
        run = p.add_run(str(h))
        set_run_font(run, ea=FONT_EA_HEAD, ascii_=FONT_ASCII_HEAD,
                     size=header_size, bold=True)
        _shade(hdr[i], "DCE3F0")

    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ""
            p = cells[i].paragraphs[0]
            p.paragraph_format.space_before = Pt(1.5)
            p.paragraph_format.space_after = Pt(1.5)
            p.paragraph_format.line_spacing = 1.2
            if i in align_center_cols:
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            _add_runs(p, str(val), size=size)

    if widths:
        for r_ in t.rows:
            for i, w in enumerate(widths):
                r_.cells[i].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


def _shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hexcolor)
    tcPr.append(shd)


def code_block(doc, lines, size=9):
    """等宽代码/流程块（用灰底表格模拟，保证不串行）。"""
    t = doc.add_table(rows=1, cols=1)
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    cell = t.rows[0].cells[0]
    cell.width = Cm(USABLE_CM)
    _shade(cell, "F4F6FA")
    cell.text = ""
    for idx, ln in enumerate(lines):
        p = cell.paragraphs[0] if idx == 0 else cell.add_paragraph()
        p.paragraph_format.space_before = Pt(0)
        p.paragraph_format.space_after = Pt(0)
        p.paragraph_format.line_spacing = 1.25
        run = p.add_run(ln)
        set_run_font(run, ea="Consolas", ascii_="Consolas", size=size)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


def page_break(doc):
    p = doc.add_paragraph()
    p.add_run().add_break(WD_BREAK.PAGE)


