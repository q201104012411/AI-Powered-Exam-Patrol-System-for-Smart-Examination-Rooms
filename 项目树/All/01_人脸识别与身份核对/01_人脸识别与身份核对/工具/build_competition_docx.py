def clean(text):
    """还原 HTML 实体，内容不变"""
    return str(text).replace("&lt;", "<").replace("&gt;", ">").replace("&amp;", "&")


def add_runs(par, text, size=BODY, color=None, base_bold=False):
    """支持 **加粗** 标记"""
    text = clean(text)
    for i, seg in enumerate(text.split("**")):
        if seg == "":
            continue
        r = par.add_run(seg)
        set_run_font(r, size=size, bold=(base_bold or i % 2 == 1), color=color)


def h1(t, new_page=True):
    par = doc.add_heading(clean(t), level=1)
    if new_page:
        par.paragraph_format.page_break_before = True
    return par


def h2(t):
    return doc.add_heading(clean(t), level=2)


def h3(t):
    return doc.add_heading(clean(t), level=3)


def p(text, bold=False, size=BODY, align=None, color=None, after=6, indent=0):
    par = doc.add_paragraph()
    par.paragraph_format.space_after = Pt(after)
    if indent:
        par.paragraph_format.left_indent = Cm(indent)
    if align is not None:
        par.alignment = align
    add_runs(par, text, size=size, color=color, base_bold=bold)
    return par


def bullet(text, level=0):
    par = doc.add_paragraph(style="List Bullet")
    par.paragraph_format.left_indent = Cm(0.75 + level * 0.6)
    par.paragraph_format.space_after = Pt(3)
    par.paragraph_format.line_spacing = 1.18
    add_runs(par, text)
    return par


def fig(text):
    """图占位：浅底灰字居中"""
    par = doc.add_paragraph()
    par.alignment = WD_ALIGN_PARAGRAPH.CENTER
    par.paragraph_format.space_before = Pt(4)
    par.paragraph_format.space_after = Pt(8)
    ppr = par._p.get_or_add_pPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:fill"), "F2F5FA")
    ppr.append(shd)
    r = par.add_run(clean(text))
    set_run_font(r, size=9, color=GREY)
    return par


def note(text):
    par = doc.add_paragraph()
    par.paragraph_format.space_after = Pt(6)
    add_runs(par, text, size=9, color=GREY)
    return par


def shade(cell, color):
    tcpr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), color)
    tcpr.append(shd)


def cell_text(cell, text, bold=False, size=9.5, color=None, align=None):
    cell.text = ""
    par = cell.paragraphs[0]
    par.paragraph_format.space_before = Pt(1.5)
    par.paragraph_format.space_after = Pt(1.5)
    par.paragraph_format.line_spacing = 1.08
    if align is not None:
        par.alignment = align
    for i, line in enumerate(clean(text).split("\n")):
        if i:
            par = cell.add_paragraph()
            par.paragraph_format.space_before = Pt(0)
            par.paragraph_format.space_after = Pt(1.5)
            par.paragraph_format.line_spacing = 1.08
            if align is not None:
                par.alignment = align
        add_runs(par, line, size=size, color=color, base_bold=bold)


def table(headers, rows, widths, font=9.5):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    hdr = t.rows[0]
    trpr = hdr._tr.get_or_add_trPr()
    th = OxmlElement("w:tblHeader")
    th.set(qn("w:val"), "true")
    trpr.append(th)
    for i, ht in enumerate(headers):
        cell_text(hdr.cells[i], ht, True, font, RGBColor(0xFF, 0xFF, 0xFF), WD_ALIGN_PARAGRAPH.CENTER)
        shade(hdr.cells[i], "1B3A6B")
    for ri, row in enumerate(rows):
        cells = t.add_row().cells
        for ci, v in enumerate(row):
            cell_text(cells[ci], v, size=font)
            if ri % 2 == 1:
                shade(cells[ci], "F2F5FA")
    for ri in range(len(t.rows)):
        for ci, w in enumerate(widths):
            t.rows[ri].cells[ci].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


