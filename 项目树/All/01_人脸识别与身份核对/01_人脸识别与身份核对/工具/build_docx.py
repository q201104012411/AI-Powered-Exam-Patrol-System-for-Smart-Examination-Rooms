def h1(t, new_page=True):
    par = doc.add_heading(t, level=1)
    if new_page:
        # 用“段前分页”代替空段落分页，避免产生整页空白
        par.paragraph_format.page_break_before = True
    return par


def h2(t):
    return doc.add_heading(t, level=2)


def h3(t):
    return doc.add_heading(t, level=3)


def p(text, bold=False, size=BODY_SIZE, align=None, color=None, after=6, indent=0):
    par = doc.add_paragraph()
    par.paragraph_format.space_after = Pt(after)
    if indent:
        par.paragraph_format.left_indent = Cm(indent)
    if align is not None:
        par.alignment = align
    r = par.add_run(text)
    set_run_font(r, size=size, bold=bold, color=color)
    return par


def bullet(text, level=0):
    par = doc.add_paragraph(style="List Bullet")
    par.paragraph_format.left_indent = Cm(0.75 + level * 0.6)
    par.paragraph_format.space_after = Pt(3)
    par.paragraph_format.line_spacing = 1.18
    if "：" in text and len(text.split("：")[0]) <= 16:
        head, tail = text.split("：", 1)
        r1 = par.add_run(head + "：")
        set_run_font(r1, bold=True)
        r2 = par.add_run(tail)
        set_run_font(r2)
    else:
        r = par.add_run(text)
        set_run_font(r)
    return par


def shade(cell, color):
    tcpr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), color)
    tcpr.append(shd)


def set_cell_text(cell, text, bold=False, size=9.5, color=None, align=None):
    cell.text = ""
    par = cell.paragraphs[0]
    par.paragraph_format.space_before = Pt(1.5)
    par.paragraph_format.space_after = Pt(1.5)
    par.paragraph_format.line_spacing = 1.08
    if align is not None:
        par.alignment = align
    for i, line in enumerate(str(text).split("\n")):
        if i:
            par = cell.add_paragraph()
            par.paragraph_format.space_before = Pt(0)
            par.paragraph_format.space_after = Pt(1.5)
            par.paragraph_format.line_spacing = 1.08
            if align is not None:
                par.alignment = align
        r = par.add_run(line)
        set_run_font(r, size=size, bold=bold, color=color)


def table(headers, rows, widths, font=9.5, caption=None, first_col_left=True, repeat_head=True):
    if caption:
        cp = doc.add_paragraph()
        cp.paragraph_format.space_after = Pt(3)
        cp.paragraph_format.space_before = Pt(6)
        r = cp.add_run(caption)
        set_run_font(r, size=10, bold=True, color=ACCENT2)
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    hdr = t.rows[0]
    if repeat_head:
        trpr = hdr._tr.get_or_add_trPr()
        th = OxmlElement("w:tblHeader")
        th.set(qn("w:val"), "true")
        trpr.append(th)
    for i, htext in enumerate(headers):
        set_cell_text(hdr.cells[i], htext, bold=True, size=font, color=RGBColor(0xFF, 0xFF, 0xFF),
                      align=WD_ALIGN_PARAGRAPH.CENTER)
        shade(hdr.cells[i], "1F3864")
    for ri, row in enumerate(rows):
        cells = t.add_row().cells
        for ci, val in enumerate(row):
            al = WD_ALIGN_PARAGRAPH.CENTER if (ci == 0 and not first_col_left) else None
            set_cell_text(cells[ci], val, size=font, align=al)
            if ri % 2 == 1:
                shade(cells[ci], "F2F5FA")
    for ri in range(len(t.rows)):
        for ci, w in enumerate(widths):
            t.rows[ri].cells[ci].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


